/**
 * HU-008: Generación automática de JSON Schema y structs Rust desde `packages/contracts`.
 * HU-009: Verificador de compatibilidad hacia atrás (`BACKWARD`) de esquemas de eventos.
 * HU-497: Generación automática de OpenAPI 3.1 para todos los endpoints expuestos.
 */

export interface FieldDescriptor {
  name: string;
  type: "string" | "integer" | "boolean" | "array" | "object";
  required: boolean;
}

export interface SchemaDescriptor {
  eventType: string;
  schemaVersion: number;
  fields: FieldDescriptor[];
}

export interface BackwardCompatibilityViolation {
  eventType: string;
  schemaVersion: number;
  kind: "REMOVED_FIELD" | "TYPE_CHANGED" | "NEW_REQUIRED_FIELD_WITHOUT_VERSION_BUMP";
  field: string;
  message: string;
}

/**
 * HU-009: Verifica compatibilidad BACKWARD entre una versión publicada de un contrato
 * y una versión modificada con el mismo `schemaVersion`.
 */
export function checkBackwardCompatibility(
  baseline: SchemaDescriptor,
  candidate: SchemaDescriptor
): BackwardCompatibilityViolation[] {
  const violations: BackwardCompatibilityViolation[] = [];
  if (
    baseline.eventType !== candidate.eventType ||
    baseline.schemaVersion !== candidate.schemaVersion
  ) {
    return violations;
  }

  const baseMap = new Map(baseline.fields.map((f) => [f.name, f]));
  const candMap = new Map(candidate.fields.map((f) => [f.name, f]));

  for (const [name, baseField] of baseMap.entries()) {
    const candField = candMap.get(name);
    if (!candField) {
      violations.push({
        eventType: candidate.eventType,
        schemaVersion: candidate.schemaVersion,
        kind: "REMOVED_FIELD",
        field: name,
        message: `El campo '${name}' fue eliminado en v${candidate.schemaVersion}; crea una nueva versión de esquema.`
      });
      continue;
    }
    if (candField.type !== baseField.type) {
      violations.push({
        eventType: candidate.eventType,
        schemaVersion: candidate.schemaVersion,
        kind: "TYPE_CHANGED",
        field: name,
        message: `El tipo de '${name}' cambió de '${baseField.type}' a '${candField.type}' en v${candidate.schemaVersion}.`
      });
    }
  }

  for (const [name, candField] of candMap.entries()) {
    const baseField = baseMap.get(name);
    if (!baseField && candField.required) {
      violations.push({
        eventType: candidate.eventType,
        schemaVersion: candidate.schemaVersion,
        kind: "NEW_REQUIRED_FIELD_WITHOUT_VERSION_BUMP",
        field: name,
        message: `Se agregó el campo obligatorio '${name}' sin incrementar schema_version (debe ser opcional o subir a v${candidate.schemaVersion + 1}).`
      });
    }
  }

  return violations;
}

/**
 * HU-008: Genera el código Rust (`#[derive(Debug, Clone, Serialize, Deserialize)]`)
 * a partir de los descriptores de contratos para el núcleo Tauri.
 */
export function generateRustContractsCode(schemas: SchemaDescriptor[]): string {
  const lines: string[] = [
    "// AUTO-GENERATED BY @tiendita/contracts — DO NOT EDIT MANUALLY (HU-008)",
    "use serde::{Deserialize, Serialize};",
    ""
  ];

  for (const schema of schemas) {
    const structName =
      schema.eventType
        .split(/[._-]/)
        .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
        .join("") + `V${schema.schemaVersion}`;

    lines.push("#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]");
    lines.push(`pub struct ${structName} {`);
    for (const field of schema.fields) {
      const rustType =
        field.type === "string"
          ? "String"
          : field.type === "integer"
            ? "i64"
            : field.type === "boolean"
              ? "bool"
              : field.type === "array"
                ? "Vec<serde_json::Value>"
                : "serde_json::Value";
      const finalType = field.required ? rustType : `Option<${rustType}>`;
      lines.push(`    pub ${field.name}: ${finalType},`);
    }
    lines.push("}");
    lines.push("");
  }

  return lines.join("\n");
}

